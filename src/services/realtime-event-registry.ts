// ── Exports ───────────────────────────────────────────────────────────────────

export const REALTIME_EVENT_REGISTRY: Readonly<Record<AuditAction, RealtimeEventConfig>> = AUDIT_TO_OPERATIONS

export const REALTIME_AUDIT_ACTIONS = Object.keys(REALTIME_EVENT_REGISTRY) as AuditAction[]

export function getRealtimeConfig(action: AuditAction): RealtimeEventConfig {
  return REALTIME_EVENT_REGISTRY[action]
}

export function getOperationalAuditActions(): AuditAction[] {
  return REALTIME_AUDIT_ACTIONS.filter(
    (a) => REALTIME_EVENT_REGISTRY[a].affectsOrders ||
           REALTIME_EVENT_REGISTRY[a].affectsKitchen ||
           REALTIME_EVENT_REGISTRY[a].affectsReservations,
  )
}

export function getHighPriorityOperationsActions(): AuditAction[] {
  return REALTIME_AUDIT_ACTIONS.filter(
    (a) => REALTIME_EVENT_REGISTRY[a].priority === 'high' ||
           REALTIME_EVENT_REGISTRY[a].priority === 'critical',
  )
}

export function getCriticalOperationsActions(): AuditAction[] {
  return REALTIME_AUDIT_ACTIONS.filter((a) => REALTIME_EVENT_REGISTRY[a].priority === 'critical')
}

export function getActionsByChannel(channel: OperationsChannelName): AuditAction[] {
  return REALTIME_AUDIT_ACTIONS.filter((a) => REALTIME_EVENT_REGISTRY[a].channels.includes(channel))
}

export function getSLATriggeredActions(): AuditAction[] {
  return REALTIME_AUDIT_ACTIONS.filter((a) => REALTIME_EVENT_REGISTRY[a].requiresSLACheck)
}

/** Cross-registry verification: every AuditAction has both a notification and an operations config. */
export function verifyRealtimeRegistryConsumesUpstream(): boolean {
  const auditActions = Object.keys(AUDIT_EVENT_REGISTRY) as AuditAction[]
  const notifActions = Object.keys(NOTIFICATION_EVENT_REGISTRY) as AuditAction[]
  const opsActions = Object.keys(REALTIME_EVENT_REGISTRY) as AuditAction[]
  return (
    auditActions.every((a) => notifActions.includes(a)) &&
    auditActions.every((a) => opsActions.includes(a))
  )
}

export function getAuditMetaForOperation(action: AuditAction) {
  return getAuditEventMeta(action)
}
